"use client";
import { ROUTES } from "@namilux/core/client";
import type { SearchIndexEntry } from "@namilux/core/client";
import { useEffect, useState } from "react";

type IndexState = { index: SearchIndexEntry[] | null; loading: boolean; error: boolean };

// One module-level cache for the whole page: the overlay, `/search/`, RecentlyViewed and the
// wishlist island all mount this hook, and exactly one request must leave the browser. The HTTP
// cache + the service worker (`nl-data-<build>`, the spec) own revalidation via ETag - the hook
// never adds a cache-busting parameter, which would defeat both.
let cached: SearchIndexEntry[] | null = null;
let inflight: Promise<void> | null = null;
let failed = false;

/**
 * DECISION: the entries are shape-checked, not zod-parsed. The file is first-party and generated by
 * `buildSearchIndex`, the hot path runs on every visitor's first search, and a bad row must never
 * throw inside a client island - so an unknown row is dropped and the rest of the index still works.
 */
function isEntry(v: unknown): v is SearchIndexEntry {
  if (typeof v !== "object" || v === null) return false;
  const o = v as Record<string, unknown>;
  return (
    typeof o["id"] === "number" &&
    typeof o["slug"] === "string" &&
    typeof o["dn"] === "string" &&
    typeof o["b"] === "string" &&
    typeof o["p"] === "number" &&
    typeof o["s"] === "boolean" &&
    Array.isArray(o["c"])
  );
}

function snapshot(): IndexState {
  if (cached !== null) return { index: cached, loading: false, error: false };
  if (failed) return { index: null, loading: false, error: true };
  return { index: null, loading: inflight !== null, error: false };
}

function load(): Promise<void> {
  if (inflight !== null) return inflight;
  failed = false;
  inflight = fetch(ROUTES.searchIndex, { credentials: "omit" })
    .then(async (res) => {
      if (!res.ok) throw new Error(`search index: ${String(res.status)}`);
      const body: unknown = await res.json();
      if (!Array.isArray(body)) throw new Error("search index: not an array");
      cached = body.filter(isEntry);
    })
    .catch(() => {
      // The route does not exist yet, the network is down, or the payload is not what we generate:
      // in every case search degrades to the idle state (never a thrown error inside the overlay).
      failed = true;
    })
    .finally(() => {
      inflight = null;
    });
  return inflight;
}

export function useSearchIndex(enabled: boolean): { index: SearchIndexEntry[] | null; loading: boolean; error: boolean } {
  // The server render is always the "not loaded yet" state, so the first client render matches it.
  const [state, setState] = useState<IndexState>({ index: null, loading: false, error: false });

  useEffect(() => {
    if (!enabled) return undefined;
    if (cached !== null) {
      setState(snapshot());
      return undefined;
    }
    let alive = true;
    setState({ index: null, loading: true, error: false });
    // DECISION: a previous failure is retried whenever the hook is enabled again - being enabled is
    // a user action (opening the overlay), so this is at most one request per attempt to search and
    // a transient offline moment does not kill search for the rest of the session.
    void load().then(() => {
      if (alive) setState(snapshot());
    });
    return () => {
      alive = false;
    };
  }, [enabled]);

  return state;
}
