/** «محصولات (۱٬۲۲۲)» → «محصولات»; a title without a count passes through unchanged. */
const COUNT_SUFFIX = /\s*\([۰-۹0-9٠-٩٬،,\s]+\)\s*$/;

export function pageGuidance(title: string): string | undefined {
  return PAGE_GUIDANCE[title.replace(COUNT_SUFFIX, "").trim()];
}
